#!/usr/bin/env node
/**
 * Generates the demo Launch Certificates used by /verify.
 *
 * The private key only lives in this process. The public key and pre-signed
 * bundles are written to src/lib/data/demo-certs.ts. Replace the public key
 * with your production signing key before shipping a real certificate flow.
 */
import { createHash, generateKeyPairSync, sign } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));

const TOTAL_RULES = 43;

function canonicalize(value) {
	if (Array.isArray(value)) {
		return `[${value.map((item) => canonicalize(item)).join(',')}]`;
	}
	if (value && typeof value === 'object') {
		return `{${Object.keys(value)
			.sort()
			.map((key) => `${JSON.stringify(key)}:${canonicalize(value[key])}`)
			.join(',')}}`;
	}
	return JSON.stringify(value);
}

const b64url = (buffer) =>
	Buffer.from(buffer).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');

const payloadBytes = (payload) => Buffer.from(canonicalize(payload), 'utf8');

function bundle(payload, signature) {
	return b64url(Buffer.from(JSON.stringify({ payload, signature }), 'utf8'));
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519');
const spki = publicKey.export({ type: 'spki', format: 'der' });
const rawPublicKey = spki.subarray(spki.length - 32);
const publicKeyB64Url = b64url(rawPublicKey);
const fingerprint = createHash('sha256')
	.update(rawPublicKey)
	.digest('hex')
	.slice(0, 32)
	.match(/.{1,4}/g)
	.join(' ')
	.toUpperCase();

const verifiedPayload = {
	v: 1,
	projectName: 'acme-saas',
	repo: 'github.com/acme/acme-saas',
	commitSha: '9c4e21a8d3f1b7c2e6a4905d1f8b3c7a2e6d4f90',
	timestamp: '2026-10-19T16:42:00.000Z',
	overallScore: 100,
	passedRules: TOTAL_RULES,
	totalRules: TOTAL_RULES,
	blockers: 0,
	failedRules: [],
	subprocessors: ['Stripe, Inc.', 'OpenAI, L.L.C.', 'Supabase, Inc.', 'PostHog, Inc.'],
	auditor: 'Preflight Avionics Engine v1.0.0',
	legalVersion: '1.5.0',
	jurisdiction: 'Delaware, US',
	nonce: 'demo_7f3a9c1e'
};

const blockedPayload = {
	v: 1,
	projectName: 'vibe-launch-mvp',
	repo: 'github.com/vibe/launch-mvp',
	commitSha: 'b128ff4a9c02e7d3158f6b0a4c9d2e7f1a3b5c68',
	timestamp: '2026-10-18T09:14:00.000Z',
	overallScore: 65,
	passedRules: 37,
	totalRules: TOTAL_RULES,
	blockers: 3,
	failedRules: ['SEC-01', 'LEG-02', 'FIN-01', 'PRIV-04', 'SEC-09', 'LEG-04'],
	subprocessors: ['Stripe, Inc.', 'Supabase, Inc.'],
	auditor: 'Preflight Avionics Engine v1.0.0',
	legalVersion: '1.2.0',
	jurisdiction: 'California (CCPA)',
	nonce: 'demo_1b6d4e8a'
};

const verifiedSignature = b64url(sign(null, payloadBytes(verifiedPayload), privateKey));
const blockedSignature = b64url(sign(null, payloadBytes(blockedPayload), privateKey));

const tamperedPayload = {
	...blockedPayload,
	overallScore: 100,
	passedRules: TOTAL_RULES,
	blockers: 0,
	failedRules: [],
	legalVersion: '1.5.0',
	subprocessors: [
		'Stripe, Inc.',
		'OpenAI, L.L.C.',
		'Supabase, Inc.',
		'PostHog, Inc.'
	]
};

const output = `// AUTO-GENERATED by scripts/generate-demo-certs.mjs — do not edit by hand.
// The demo private key is intentionally NOT committed. Replace the public key
// below with your production Ed25519 signing key before shipping real certs.

export const DEMO_PUBLIC_KEY_B64URL =
	'${publicKeyB64Url}';

export const DEMO_KEY_FINGERPRINT = '${fingerprint}';

/** Base64URL bundles containing { payload, signature }. */
export const DEMO_BUNDLES = {
	verified:
		'${bundle(verifiedPayload, verifiedSignature)}',
	blocked:
		'${bundle(blockedPayload, blockedSignature)}',
	tampered:
		'${bundle(tamperedPayload, blockedSignature)}'
} as const;

export type DemoBundleKey = keyof typeof DEMO_BUNDLES;
`;

const target = join(__dirname, '..', 'src', 'lib', 'data', 'demo-certs.ts');
writeFileSync(target, output);
console.log(`Wrote ${target}`);
console.log(`Public key: ${publicKeyB64Url}`);
console.log(`Fingerprint: ${fingerprint}`);
