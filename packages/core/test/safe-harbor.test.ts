import { afterAll, describe, expect, test } from "bun:test";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { AI_TRAINING_BOTS, compileSafeHarbor, securityContact } from "../src/compilers/safe-harbor";
import { buildRepoContext } from "../src/context/builder";
import { initSafeHarbor } from "../src/init";
import { seo01LaunchMeta } from "../src/rules/finops-ops/seo-01-launch-meta";

const DAY = 86_400_000;
const dirs: string[] = [];
afterAll(() => {
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
});
/** Temp copy of the vulnerable fixture (no robots.txt, /api routes) with extra files. */
function copy(extra: Record<string, string> = {}): string {
  const d = mkdtempSync(join(tmpdir(), "preflight-harbor-"));
  dirs.push(d);
  cpSync("fixtures/vulnerable-saas", d, { recursive: true });
  for (const [rel, text] of Object.entries(extra)) {
    mkdirSync(join(d, rel, ".."), { recursive: true });
    writeFileSync(join(d, rel), text);
  }
  return d;
}
const ctxOf = (root: string, contact = "security@northwind.io") =>
  buildRepoContext(root, { config: { offline: true, securityContact: contact, siteUrl: "https://northwind.io" } });
const read = (root: string, rel: string) => readFileSync(join(root, rel), "utf8");

describe("securityContact", () => {
  test("refuses empty and placeholder contacts, normalises real ones", () => {
    for (const bad of ["", "privacy@northwind.example", "security@example.com", "you@yourcompany.com", "[EMAIL]", "https://localhost/sec", "not a contact"])
      expect("error" in securityContact({ contactEmail: bad })).toBe(true);
    expect(securityContact({ contactEmail: "sec@acme.io" })).toEqual({ uri: "mailto:sec@acme.io" });
    expect(securityContact({ contactEmail: "x@acme.io", securityContact: "https://acme.io/security" })).toEqual({ uri: "https://acme.io/security" });
  });
});

describe("compileSafeHarbor", () => {
  test("writes RFC 9116 security.txt, SECURITY.md, robots.txt and ai.txt; idempotent", async () => {
    const root = copy({ "app/dashboard/page.tsx": "export default function D() { return null }", "app/pricing/page.tsx": "export default () => null" });
    const now = new Date();
    const first = compileSafeHarbor(await ctxOf(root), { apply: true, now });
    expect(first.skipped).toEqual([]);
    expect(first.changes.map((c) => c.path).sort()).toEqual(["SECURITY.md", "public/.well-known/security.txt", "public/ai.txt", "public/robots.txt"]);

    const txt = read(root, "public/.well-known/security.txt");
    expect(txt).toMatch(/^Contact: mailto:security@northwind\.io$/m);
    const expires = Date.parse(txt.match(/^Expires: (\S+)$/m)![1]);
    expect(expires - now.getTime()).toBeGreaterThan(300 * DAY);
    expect(expires - now.getTime()).toBeLessThan(365 * DAY);
    expect(txt).toContain("Canonical: https://northwind.io/.well-known/security.txt");
    expect(read(root, "SECURITY.md")).toContain("security@northwind.io");

    // Search crawlers: one `*` group with no Disallow. AI bots: blocked on the app only.
    const robots = read(root, "public/robots.txt");
    const groups = robots.split(/\n\s*\n/);
    const star = groups.find((g) => /^User-agent: \*$/m.test(g))!;
    expect(star).not.toMatch(/Disallow/);
    const ai = groups.find((g) => g.includes("User-agent: GPTBot"))!;
    for (const b of AI_TRAINING_BOTS) expect(ai).toContain(`User-agent: ${b}`);
    expect(ai).toContain("Disallow: /api/");
    expect(ai).toContain("Disallow: /dashboard");
    expect(ai).not.toContain("/pricing");
    expect(robots).not.toMatch(/User-agent: (Googlebot|Bingbot)/i);
    expect(read(root, "public/ai.txt")).toContain("Disallow: /dashboard");

    // SEO-01 no longer reports robots.txt.
    const seo = await seo01LaunchMeta.run(await ctxOf(root));
    expect(seo.every((f) => !f.evidence.includes("robots.txt"))).toBe(true);

    const second = compileSafeHarbor(await ctxOf(root), { apply: true, now: new Date(now.getTime() + DAY) });
    expect(second.changes).toEqual([]);
  });

  test("refuses placeholders and never overwrites human-written files", async () => {
    const root = copy({ "public/robots.txt": "User-agent: *\nDisallow:\n" });
    const r = compileSafeHarbor(await ctxOf(root, "privacy@northwind.example"), { apply: true });
    expect(existsSync(join(root, "SECURITY.md"))).toBe(false);
    expect(existsSync(join(root, "public/.well-known/security.txt"))).toBe(false);
    expect(r.skipped.map((s) => s.reason).join("\n")).toMatch(/placeholder/);
    expect(r.skipped.find((s) => s.path === "public/robots.txt")?.reason).toMatch(/wasn't generated by Preflight/);
    expect(read(root, "public/robots.txt")).toBe("User-agent: *\nDisallow:\n");
    expect(r.changes.map((c) => c.path)).toEqual(["public/ai.txt"]);
  });

  test("defers to a generated robots route; expired security.txt is refreshed", async () => {
    const root = copy({ "app/robots.ts": "export default function robots() { return { rules: [] } }" });
    const ctx = await ctxOf(root);
    compileSafeHarbor(ctx, { apply: true, now: new Date(Date.now() - 340 * DAY) });
    const r = compileSafeHarbor(await ctxOf(root), { apply: true });
    expect(r.skipped.find((s) => s.path === "public/robots.txt")?.reason).toContain("app/robots.ts");
    expect(r.changes.map((c) => c.path)).toEqual(["public/.well-known/security.txt"]);
  });

  test("init writes the bundle from the package.json author email", async () => {
    const d = mkdtempSync(join(tmpdir(), "preflight-harbor-init-"));
    dirs.push(d);
    writeFileSync(join(d, "package.json"), JSON.stringify({ name: "t", author: "Acme <security@acme.io>" }));
    const actions = await initSafeHarbor(d);
    expect(actions.filter((a) => a.action === "created").map((a) => a.path)).toContain("public/.well-known/security.txt");
    expect((await initSafeHarbor(d)).every((a) => a.action !== "created" && a.action !== "updated")).toBe(true);
  });
});
