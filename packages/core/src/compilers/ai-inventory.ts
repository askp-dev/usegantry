/**
 * EU AI Act inventory compiler (`--profile eu-ai-act`): AI_INVENTORY.md listing providers, models, embedders,
 * system prompts and the routes that call a model, from `ctx` + the sub-processor map. Deterministic (no dates),
 * so AIA-01 can detect staleness by comparison. Anything below the end marker is human-owned and preserved.
 */
import { vendorById } from "../context/knowledge";
import type { RepoContext } from "../context/types";
import { isAiVendor } from "../rules/compliance/compliance-helpers";
import { routeBody } from "../rules/helpers";

export const AI_INVENTORY_PATH = "AI_INVENTORY.md";
export const AI_INVENTORY_END = "<!-- preflight:end — everything below this line is yours and is kept on regeneration -->";

const MODEL_RE =
  /^(?:gpt-[\w.-]+|o[134](?:-[\w-]+)?|chatgpt-[\w.-]+|claude-[\w.-]+|gemini-[\w.-]+|(?:open-)?mi[sx]tral-[\w.-]+|(?:meta-)?llama-?[\w./-]*|deepseek-[\w.-]+|grok-[\w.-]+|command-[\w.-]+|text-embedding-[\w.-]+|embed-[\w.-]+|voyage-[\w.-]+|nomic-embed-[\w.-]+|whisper-[\w.-]+|dall-e-[\w.-]+|tts-[\w.-]+|sonar[\w.-]*)$/i;
const PROMPT_RE =
  /\brole\s*:\s*['"]system['"]|\bsystem\s*:\s*[`'"A-Za-z_]|\b(?:const|let|var)\s+\w*(?:SYSTEM|System|system)_?(?:PROMPT|Prompt|prompt)\w*\s*=|^\s*\w*SYSTEM_PROMPT\w*\s*=/gm;
const HITL_RE = /\b(?:approv|review|human|moderat|confirm|escalat)\w*/i;
const CODE_RE = /\.(?:[cm]?[jt]sx?|py|svelte|vue)$/;
const TEST_RE = /(^|\/)(test|tests|__tests__|fixtures)\/|\.(test|spec)\./;

const yn = (b: boolean | null | undefined) => (b === true ? "yes" : b === false ? "no" : "unknown — verify");
const cell = (s: string) => s.replace(/\|/g, "\\|");
const at = (locs: string[]) => (locs.length > 3 ? `${locs.slice(0, 3).join(", ")} (+${locs.length - 3})` : locs.join(", "));

export interface AiInventory {
  usesAi: boolean;
  /** Generated part only (up to and including the end marker). */
  generated: string;
}

export function buildAiInventory(ctx: RepoContext): AiInventory {
  const ai = ctx.detectedSubprocessors.map((s) => vendorById(s.id)).filter((v) => v && isAiVendor(v));
  const vectors = ctx.detectedSubprocessors.map((s) => vendorById(s.id)).filter((v) => v && /Vector/.test(v.category));
  const models = new Map<string, string[]>();
  const prompts: string[] = [];
  for (const file of ctx.files.all) {
    if (!CODE_RE.test(file) || TEST_RE.test(file)) continue;
    const ci = ctx.getCode(file);
    for (const m of ci.findAll(/(['"`])([\w./:@-]{2,80})\1/, "noComments")) {
      if (!MODEL_RE.test(m[2])) continue;
      const list = models.get(m[2]) ?? [];
      list.push(`${file}:${ci.lineOf(m.index)}`);
      models.set(m[2], list);
    }
    for (const m of ci.findAll(PROMPT_RE, "noComments")) prompts.push(`${file}:${ci.lineOf(m.index)}`);
  }
  const aiIds = new Set(ai.map((v) => v!.id));
  const routes = ctx.routes.filter((r) => r.externalSdksCalled.some((id) => aiIds.has(id)));
  const usesAi = ai.length > 0 || models.size > 0;

  const out = [
    "# AI System Inventory",
    "",
    "<!-- Generated by Preflight (`--profile eu-ai-act`). Regenerate with `preflight legal --apply --profile eu-ai-act`. -->",
    "",
    "Supports EU AI Act record-keeping and transparency duties (Art. 4, 26, 50). It lists what the code shows; the risk classification and oversight measures are yours to confirm.",
    "",
    "## Providers",
    "",
  ];
  if (ai.length) {
    out.push("| Provider | Entity | Jurisdiction | Zero data retention | Trains on inputs | DPA |", "|---|---|---|---|---|---|");
    for (const v of ai.sort((a, b) => a!.id.localeCompare(b!.id)))
      out.push(`| ${v!.id} | ${cell(v!.entityName)} | ${v!.jurisdiction} | ${yn(v!.zdr)} | ${yn(v!.trainsOnData)} | ${v!.dpaUrl} |`);
  } else out.push("No AI provider SDKs detected.");
  if (vectors.length) out.push("", `Vector stores: ${vectors.map((v) => `${v!.entityName} (${v!.jurisdiction})`).join(", ")}.`);

  const section = (title: string, kind: (m: string) => boolean) => {
    const rows = [...models].filter(([m]) => kind(m)).sort(([a], [b]) => a.localeCompare(b));
    out.push("", `## ${title}`, "");
    if (!rows.length) return out.push("None detected.");
    out.push("| Model | Referenced at |", "|---|---|", ...rows.map(([m, locs]) => `| \`${m}\` | ${at(locs)} |`));
  };
  section("Models", (m) => !/embed/i.test(m));
  section("Embedders", (m) => /embed/i.test(m));

  out.push("", "## System prompts", "", prompts.length ? prompts.map((p) => `- ${p}`).join("\n") : "None detected.");

  out.push("", "## Routes that call a model", "");
  if (routes.length) {
    out.push("| Route | Method | Providers | Auth | Human-in-the-loop |", "|---|---|---|---|---|");
    for (const r of [...routes].sort((a, b) => a.urlPath.localeCompare(b.urlPath) || a.method.localeCompare(b.method))) {
      const { ci, a, b } = routeBody(ctx, r);
      const hitl = HITL_RE.test(ci.slice(a, b, "masked")) ? "review step found (verify)" : "none detected";
      out.push(
        `| \`${cell(r.urlPath)}\` | ${r.method} | ${r.externalSdksCalled.filter((id) => aiIds.has(id)).join(", ")} | ${r.hasAuthGuard ? "yes" : "no"} | ${hitl} |`,
      );
    }
  } else out.push("None detected.");

  out.push("", AI_INVENTORY_END, "");
  return { usesAi, generated: out.join("\n") };
}

/** Full file content: the generated part plus the human-owned tail of the existing file (or a starter). */
export function compileAiInventory(ctx: RepoContext): Record<string, string> {
  const { usesAi, generated } = buildAiInventory(ctx);
  if (!usesAi) return {};
  const existing = ctx.getText(AI_INVENTORY_PATH);
  const i = existing.indexOf(AI_INVENTORY_END);
  const tail =
    i >= 0
      ? existing.slice(i + AI_INVENTORY_END.length + 1)
      : "\n## Risk classification and oversight\n\n- Risk class (Art. 6 / Annex III): _not yet assessed_\n- Human oversight measures: _describe_\n";
  return { [AI_INVENTORY_PATH]: generated + tail };
}

/** True when the file's generated part matches what the code shows now. */
export function aiInventoryIsCurrent(ctx: RepoContext, generated = buildAiInventory(ctx).generated): boolean {
  const existing = ctx.getText(AI_INVENTORY_PATH);
  const i = existing.indexOf(AI_INVENTORY_END);
  return i >= 0 && existing.slice(0, i + AI_INVENTORY_END.length + 1) === generated;
}
