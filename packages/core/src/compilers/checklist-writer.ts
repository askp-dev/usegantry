import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { AuditReport, RepoContext } from "../context/types";
import { ALL_STATIC_RULES } from "../rules/index";

const BEGIN = "<!-- PREFLIGHT:AUTO:CHECKLIST -->";
const END = "<!-- /PREFLIGHT:AUTO:CHECKLIST -->";
const PILLAR_TITLE = {
  SECURITY: "Security & Tenant Isolation",
  PRIVACY: "Data Protection & Privacy",
  LEGAL: "EULA, Licensing & Legal",
  FINOPS_OPS: "FinOps, Payments, Ops & A11y",
} as const;

export function renderChecklist(report: AuditReport): string {
  const lines = [
    BEGIN,
    `**Score ${report.score}/100 · ${report.status.replace("_", " ")} · ${report.blockers} blocker(s)** · ${report.repo.gitCommitSha.slice(0, 7) || "uncommitted"} · ${report.generatedAt.slice(0, 10)}`,
    "",
  ];
  for (const p of Object.keys(PILLAR_TITLE) as Array<keyof typeof PILLAR_TITLE>) {
    const ps = report.pillars.find((x) => x.pillar === p);
    lines.push(`### ${PILLAR_TITLE[p]} (${ps?.score ?? 100}/100)`, "");
    for (const r of ALL_STATIC_RULES.filter((x) => x.pillar === p)) {
      const fs = report.findings.filter((f) => f.ruleId === r.id);
      lines.push(`- [${fs.length ? " " : "x"}] **${r.id}** ${r.title}${fs.length ? ` (${fs.length})` : ""}`);
      for (const f of fs.slice(0, 10))
        lines.push(`  - ${f.blocking ? "⛔" : "⚠️"} \`${f.file}:${f.line}\` ${f.severity}: ${f.evidence.split("\n")[0].slice(0, 120)}`);
      if (fs.length > 10) lines.push(`  - …and ${fs.length - 10} more`);
    }
    lines.push("");
  }
  lines.push(END);
  return lines.join("\n");
}

/** Updates only the auto block; anything the user writes outside the markers is preserved. */
export function buildChecklist(existing: string, report: AuditReport): string {
  const block = renderChecklist(report);
  if (!existing.trim()) return `# Launch Readiness Checklist\n\nGenerated by Preflight. Add your own notes outside the auto block.\n\n${block}\n`;
  const i = existing.indexOf(BEGIN);
  const j = existing.indexOf(END);
  if (i >= 0 && j > i) return existing.slice(0, i) + block + existing.slice(j + END.length);
  return `${existing.trimEnd()}\n\n${block}\n`;
}

export function writeChecklist(ctx: RepoContext, report: AuditReport): string {
  const out = buildChecklist(ctx.getText("READINESS_CHECKLIST.md"), report);
  writeFileSync(join(ctx.rootDir, "READINESS_CHECKLIST.md"), out);
  return out;
}
