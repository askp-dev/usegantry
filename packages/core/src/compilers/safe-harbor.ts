/**
 * Safe-harbor bundle: SECURITY.md + RFC 9116 security.txt, and robots.txt + ai.txt that keep AI training
 * crawlers out of the app while search crawlers see everything. Wired into `gantry legal --sync` and `init`.
 */
import { AUTH_ASSERTION_RE, PLACEHOLDER_RE } from "../context/patterns";
import type { GantryConfig, RepoContext } from "../context/types";
import { type LegalChange, writeChanges } from "./legal-compiler";

const SAFE_HARBOR_MARK = "Generated by Gantry safe-harbor";
/** AI training crawlers / opt-out tokens. None of them feeds a search index. */
export const AI_TRAINING_BOTS = ["GPTBot", "CCBot", "ClaudeBot", "Google-Extended"] as const;
const DAY = 86_400_000;
/** RFC 9116 §2.5.5: Expires should be less than a year out. */
const EXPIRES_DAYS = 330;
const PLACEHOLDER_CONTACT =
  /(^|[@./])(example\.(com|org|net)|[\w-]+\.(example|test|invalid|localhost|local))($|[/:?#])|@(domain|company|yourcompany|yourdomain|email|test)\.(com|io)$|^(mailto:)?(you|your|name|user|me|someone|test|foo|john\.?doe|jane\.?doe)@|localhost|127\.0\.0\.1|your[-_]?(company|domain|email|site)/i;
/** First path segments (or route groups) that are the app itself, not marketing. */
const APP_SEGMENT =
  /^(api|app|dashboard|account|accounts|settings|admin|billing|chat|workspace|workspaces|projects?|studio|inbox|editor|console|profile|org|orgs|team|teams|onboarding|login|logout|signin|sign-in|signup|sign-up|register|auth|checkout|portal|protected|private|authed|authenticated|internal)$/i;
const PAGE_FILE =
  /^(?:src\/)?app\/(.*?)\/?(?:page|layout)\.(?:[jt]sx?|mdx)$|^(?:src\/)?pages\/(?!api\/|_)(.+?)\.(?:[jt]sx?|mdx)$|^src\/routes\/(.*?)\/?\+(?:page|layout)(?:\.server)?\.(?:svelte|[jt]s)$|^app\/routes\/([^/]+?)\.[jt]sx?$/;
const ROBOTS_ROUTE = /(^|\/)(src\/)?app\/robots\.(ts|js)$|(^|\/)routes\/robots\.txt\/\+server\.[tj]s$/;

interface SafeHarborResult {
  changes: LegalChange[];
  skipped: Array<{ path: string; reason: string }>;
}

/** The security contact as an RFC 9116 URI, or why it can't be used. Placeholders are refused, never published. */
export function securityContact(cfg: Pick<GantryConfig, "securityContact" | "contactEmail">): { uri: string } | { error: string } {
  const raw = (cfg.securityContact || cfg.contactEmail || "").trim();
  if (!raw) return { error: "no contact: set `securityContact` (email or https URL) in gantry.config.json" };
  if (PLACEHOLDER_RE.test(raw) || PLACEHOLDER_CONTACT.test(raw)) return { error: `contact "${raw}" is a placeholder; set a real \`securityContact\`` };
  if (/^mailto:[^@\s]+@[^@\s]+\.[a-z]{2,}$/i.test(raw) || /^tel:\+?[\d-]+$/.test(raw) || /^https:\/\/[^\s/]+\.[^\s/]+/.test(raw)) return { uri: raw };
  if (/^[^@\s:/]+@[^@\s/]+\.[a-z]{2,}$/i.test(raw)) return { uri: `mailto:${raw}` };
  return { error: `contact "${raw}" must be an email, mailto:, tel: or https:// URL` };
}

/** Production origin, only when it's a real https URL. */
function siteOrigin(cfg: GantryConfig): string | null {
  const s = cfg.siteUrl?.trim().replace(/\/+$/, "");
  return s && /^https:\/\/[^\s/]+\.[^\s/]+$/.test(s) && !PLACEHOLDER_CONTACT.test(s) ? s : null;
}

/** Top-level path prefixes of the app (API + authenticated / app-shell pages), sorted. Marketing and legal pages are left out. */
function appPrefixes(ctx: RepoContext): string[] {
  const out = new Set<string>();
  for (const r of ctx.routes) {
    const seg = r.urlPath.split("/")[1];
    if (seg === "api") out.add("/api/");
    else if (seg && r.method !== "SERVER_ACTION" && !seg.startsWith("[") && !seg.startsWith(":")) out.add(`/${seg}`);
  }
  for (const f of ctx.files.all) {
    const m = f.match(PAGE_FILE);
    if (!m) continue;
    const parts = (m[1] ?? m[2] ?? m[3] ?? m[4]?.replace(/\./g, "/") ?? "").split("/").filter(Boolean);
    const groups = parts.filter((p) => /^\(.+\)$/.test(p)).map((p) => p.slice(1, -1));
    const seg = parts.find((p) => !/^\(.+\)$/.test(p) && p !== "index" && p !== "_index");
    if (!seg || /^[[:$_]/.test(seg)) continue;
    if (APP_SEGMENT.test(seg) || groups.some((g) => APP_SEGMENT.test(g)) || AUTH_ASSERTION_RE.test(ctx.getCode(f).masked)) out.add(`/${seg}`);
  }
  return [...out].sort();
}

function robotsTxt(app: string[], origin: string | null): string {
  return [
    `# ${SAFE_HARBOR_MARK} (\`gantry legal --sync\`). Delete this line to take ownership.`,
    "# Search engines: everything public stays crawlable.",
    "User-agent: *",
    "Allow: /",
    "",
    "# AI training crawlers: marketing pages only, never the app.",
    ...AI_TRAINING_BOTS.map((b) => `User-agent: ${b}`),
    ...app.map((p) => `Disallow: ${p}`),
    "Allow: /",
    ...(origin ? ["", `Sitemap: ${origin}/sitemap.xml`] : []),
    "",
  ].join("\n");
}

function aiTxt(app: string[]): string {
  return [
    `# ${SAFE_HARBOR_MARK}. ai.txt (spawning.ai): what AI training may use from this site.`,
    "User-Agent: *",
    ...app.map((p) => `Disallow: ${p}`),
    "Allow: /",
    "",
  ].join("\n");
}

function securityTxt(contact: string, expires: string, origin: string | null): string {
  return [
    `# ${SAFE_HARBOR_MARK} (RFC 9116). Re-run \`gantry legal --sync\` before it expires.`,
    `Contact: ${contact}`,
    `Expires: ${expires}`,
    ...(origin ? [`Canonical: ${origin}/.well-known/security.txt`] : []),
    "Preferred-Languages: en",
    "",
  ].join("\n");
}

function securityMd(cfg: GantryConfig, contact: string): string {
  const who = cfg.companyName || cfg.productName || "We";
  const reach = contact.replace(/^mailto:/, "");
  return `<!-- ${SAFE_HARBOR_MARK}. Delete this line to take ownership. -->
# Security Policy

## Reporting a vulnerability

${contact.startsWith("mailto:") ? "Email" : "Contact"} **${reach}**. Please don't open a public issue. Include the affected URL or file, steps to reproduce, and the impact you observed. We aim to acknowledge reports within 3 business days and to keep you updated until the issue is fixed.

## Safe harbor

${who === "We" ? "We consider" : `${who} considers`} security research carried out in good faith under this policy to be authorized. We won't pursue or support legal action against you for it, and if a third party takes action against you over research that followed this policy, we'll make it known that your work was authorized. Good faith means you:

- only test accounts and data you own, or have the owner's explicit permission to test;
- stop as soon as you reach other people's data, don't keep or share it, and tell us what you accessed;
- don't degrade the service (no denial of service, spam, social engineering or physical attacks);
- give us reasonable time (90 days by default) to fix the issue before you disclose it publicly.

## Scope

In scope: ${cfg.productName || "this application"}, its API and this repository. Out of scope: third-party services we use (report those to the vendor), volumetric or denial-of-service testing, and findings that need a compromised device.

_This template isn't legal advice. Have counsel review it before you rely on it._
`;
}

export function compileSafeHarbor(ctx: RepoContext, opts: { apply?: boolean; now?: Date } = {}): SafeHarborResult {
  const cfg = ctx.config;
  const now = opts.now ?? new Date();
  const skipped: SafeHarborResult["skipped"] = [];
  const files: Record<string, string> = {};
  const all = ctx.files.all;
  const pub = !all.some((f) => f.startsWith("public/")) && all.some((f) => f.startsWith("static/") || /^svelte\.config\./.test(f)) ? "static" : "public";
  /** Never overwrite a file a human wrote: only create, or update one that still carries our marker. */
  const put = (path: string, text: string) => {
    const before = ctx.getText(path);
    if (before && !before.includes(SAFE_HARBOR_MARK)) skipped.push({ path, reason: "exists and wasn't generated by Gantry; left untouched" });
    else files[path] = text;
  };

  const contact = securityContact(cfg);
  const origin = siteOrigin(cfg);
  if ("error" in contact) skipped.push({ path: `SECURITY.md, ${pub}/.well-known/security.txt`, reason: contact.error });
  else {
    const other = all.find((f) => /^(\.github|docs)\/SECURITY\.md$/i.test(f));
    if (other) skipped.push({ path: "SECURITY.md", reason: `${other} already exists` });
    else put("SECURITY.md", securityMd(cfg, contact.uri));
    // Keep a still-valid Expires so re-running is idempotent; refresh it once fewer than 30 days remain.
    const txtPath = `${pub}/.well-known/security.txt`;
    const prev = ctx.getText(txtPath).match(/^Expires:\s*(\S+)/m)?.[1];
    const prevMs = prev ? Date.parse(prev) : Number.NaN;
    const expires =
      prev && prevMs - now.getTime() > 30 * DAY && prevMs - now.getTime() < 366 * DAY
        ? prev
        : new Date(now.getTime() + EXPIRES_DAYS * DAY).toISOString().replace(/\.\d{3}Z$/, "Z");
    put(txtPath, securityTxt(contact.uri, expires, origin));
  }

  const app = appPrefixes(ctx);
  const route = all.find((f) => ROBOTS_ROUTE.test(f));
  if (route)
    skipped.push({
      path: `${pub}/robots.txt`,
      reason: `${route} generates robots.txt; add a rule for ${AI_TRAINING_BOTS.join(", ")} with disallow [${app.join(", ")}] there`,
    });
  else put(`${pub}/robots.txt`, robotsTxt(app, origin));
  put(`${pub}/ai.txt`, aiTxt(app));

  return { changes: writeChanges(ctx, files, opts.apply), skipped };
}
